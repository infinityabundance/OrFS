#!/bin/sh
# OrFS one-command continuous verification (Phase 73; reviewer item #12).
#
# The pre-PR entry point: one script that runs every court this project checks
# before a change is accepted, **one container at a time**, and prints a
# PASS/FAIL/SKIPPED summary per stage. It exits non-zero if any stage fails.
#
# Stages, in order:
#   1. `check-all` (fast): fmt/clippy + docs<->evidence receipts + chart drift
#   2. the default test suite
#   3. the default test suite with `--features failpoints` (crash-injection court)
#   4. the POSIX court (pjdfstest + POSIX ops; needs `/dev/fuse`)
#   5. the native fsx/fsstress-equivalent fault-injection court
#   6. the io_uring court (integration + backing benchmark)
#   7. the bounded Loom concurrency model
#   8. the docs<->evidence receipts check again, at the end
#
# A stage that cannot run in this environment (the POSIX court without
# `/dev/fuse`, or any container stage without a usable Docker daemon) is
# reported `SKIPPED (reason)` and is **not** counted as a pass.
#
# `--fast` runs only the cheap, always-available parts — fmt/clippy,
# docs-receipts, chart drift, and the default test suite — and skips the
# failpoint suite and every court that needs a mount (`/dev/fuse`) or is heavy.
#
# One container runs at a time: the stage scripts are invoked sequentially and
# each uses the shared `scripts/lib.sh` docker helpers (never the host).
#
# The suites regenerate evidence receipts as a side effect (the project's
# `check-all` runs the docs-receipts check *before* the suite for this reason).
# So before the final docs-receipts stage this runner restores the tracked
# evidence files that the run itself rewrote, keeping any file that was already
# modified when the run began. The final check therefore validates the evidence
# state under review, not throwaway timing churn, and the tree is left clean.
#
# Usage:
#   sh scripts/container-verify.sh          # full pre-PR court
#   sh scripts/container-verify.sh --fast   # cheap/always-available subset
set -eu

DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
# lib.sh resolves the project root, the memory caps and the docker helpers.
. "$DIR/lib.sh"
# The runner must survive a failing stage so it can print the whole summary and
# still exit non-zero. Each stage script runs as its own process with its own
# `set -e`, so disabling errexit here does not weaken them.
set +e

FAST=0
case "${1:-}" in
    --fast) FAST=1 ;;
    "") ;;
    *)
        echo "orfs: container-verify: unknown argument: $1 (use --fast)" >&2
        exit 2
        ;;
esac

have_docker() { command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; }

if have_docker; then HAVE_DOCKER=1; else HAVE_DOCKER=0; fi
if [ -e /dev/fuse ]; then HAVE_FUSE=1; else HAVE_FUSE=0; fi

# The suites and some courts regenerate evidence receipts as a side effect. Those
# regenerations are throwaway timing churn, not the state under review, so the
# final docs-receipts stage must check the tree as it was when the run started.
# Record which tracked evidence files were already modified *before* the run, so
# the restore below never discards a developer's own uncommitted evidence change.
EVIDENCE_PRE_EXISTING=""
HAVE_GIT=0
if [ -d "$ORFS_PROJECT_DIR/evidence" ] && \
   git -C "$ORFS_PROJECT_DIR" rev-parse --git-dir >/dev/null 2>&1; then
    HAVE_GIT=1
    EVIDENCE_PRE_EXISTING="$(git -C "$ORFS_PROJECT_DIR" diff --name-only -- evidence 2>/dev/null)"
fi

# Restore tracked evidence the run itself rewrote, keeping files that were already
# modified when the run began. This makes the final consistency check (and the
# tree it leaves behind) reflect the committed/initial evidence state; a receipt a
# developer wants to refresh is regenerated by its dedicated court and committed.
restore_run_churned_evidence() {
    [ "$HAVE_GIT" -eq 1 ] || return 0
    for p in $(git -C "$ORFS_PROJECT_DIR" diff --name-only -- evidence 2>/dev/null); do
        if printf '%s\n' "$EVIDENCE_PRE_EXISTING" | grep -F -x -q -- "$p"; then
            continue
        fi
        git -C "$ORFS_PROJECT_DIR" checkout -- "$p" 2>/dev/null || true
    done
}

STAGE=0
TOTAL=8
FAILED=0
SKIPPED=0
SUMMARY=""

_status() {
    SUMMARY="$SUMMARY$1
"
}

run_stage() {
    label="$1"
    shift
    STAGE=$((STAGE + 1))
    printf '\n=== verify stage %d/%d: %s ===\n' "$STAGE" "$TOTAL" "$label"
    if "$@"; then
        _status "PASS     stage $STAGE/$TOTAL  $label"
    else
        rc=$?
        _status "FAIL     stage $STAGE/$TOTAL  $label  (exit $rc)"
        FAILED=$((FAILED + 1))
    fi
}

skip_stage() {
    label="$1"
    reason="$2"
    STAGE=$((STAGE + 1))
    printf '\n=== verify stage %d/%d: %s ===\n' "$STAGE" "$TOTAL" "$label"
    printf 'SKIPPED: %s\n' "$reason"
    _status "SKIPPED  stage $STAGE/$TOTAL  $label  ($reason)"
    SKIPPED=$((SKIPPED + 1))
}

run_or_skip_docker() {
    label="$1"
    shift
    if [ "$HAVE_DOCKER" -eq 1 ]; then
        run_stage "$label" "$@"
    else
        skip_stage "$label" "docker unavailable"
    fi
}

printf 'orfs: container-verify: %s (docker=%s fuse=%s)\n' \
    "$([ "$FAST" -eq 1 ] && echo fast || echo full)" \
    "$([ "$HAVE_DOCKER" -eq 1 ] && echo yes || echo no)" \
    "$([ "$HAVE_FUSE" -eq 1 ] && echo yes || echo no)"

# --- stage 1: cheap deterministic gate -------------------------------------
if [ "$HAVE_DOCKER" -eq 1 ]; then
    run_stage "check-all (fast): fmt/clippy + docs-receipts + chart drift" \
        sh "$DIR/check-all.sh" --fast
else
    run_stage "docs-receipts + chart drift (host; Docker unavailable)" \
        sh -c "sh '$DIR/check-docs-receipts.sh' && python3 '$DIR/render_charts.py' --check"
fi

# --- stage 2: default test suite -------------------------------------------
run_or_skip_docker "default test suite" sh "$DIR/container-test.sh"

# --- stage 3: failpoints test suite ----------------------------------------
if [ "$FAST" -eq 1 ]; then
    skip_stage "default test suite (--features failpoints)" "--fast"
else
    run_or_skip_docker "default test suite (--features failpoints)" \
        sh "$DIR/container-test.sh" --features failpoints
fi

# --- stage 4: POSIX court (needs /dev/fuse) --------------------------------
if [ "$FAST" -eq 1 ]; then
    skip_stage "POSIX court (pjdfstest + POSIX ops)" "--fast"
elif [ "$HAVE_DOCKER" -eq 0 ]; then
    skip_stage "POSIX court (pjdfstest + POSIX ops)" "docker unavailable"
elif [ "$HAVE_FUSE" -eq 0 ]; then
    skip_stage "POSIX court (pjdfstest + POSIX ops)" "no /dev/fuse"
else
    run_stage "POSIX court (pjdfstest + POSIX ops)" sh "$DIR/container-posix-test.sh"
fi

# --- stage 5: native fsx/fsstress fault-injection court --------------------
if [ "$FAST" -eq 1 ]; then
    skip_stage "native fsx/fsstress fault-injection court" "--fast"
else
    run_or_skip_docker "native fsx/fsstress fault-injection court" \
        sh "$DIR/container-fault-injection.sh"
fi

# --- stage 6: io_uring court -----------------------------------------------
if [ "$FAST" -eq 1 ]; then
    skip_stage "io_uring court (integration + backing benchmark)" "--fast"
else
    run_or_skip_docker "io_uring court (integration + backing benchmark)" \
        sh "$DIR/container-uring-test.sh"
fi

# --- stage 7: bounded Loom model -------------------------------------------
if [ "$FAST" -eq 1 ]; then
    skip_stage "bounded Loom concurrency model" "--fast"
else
    run_or_skip_docker "bounded Loom concurrency model" sh "$DIR/container-loom.sh"
fi

# --- stage 8: docs-receipts re-check at the end ----------------------------
restore_run_churned_evidence
run_stage "docs-receipts (final re-check)" sh "$DIR/check-docs-receipts.sh"

# --- summary ---------------------------------------------------------------
printf '\n=== verify summary ===\n%s' "$SUMMARY"

if [ "$FAILED" -ne 0 ]; then
    printf '\nverify: FAIL — %d stage(s) failed, %d skipped\n' "$FAILED" "$SKIPPED"
    exit 1
fi
if [ "$SKIPPED" -ne 0 ]; then
    printf '\nverify: PASS (%d stage(s) skipped — not counted as pass)\n' "$SKIPPED"
    exit 0
fi
printf '\nverify: PASS — all %d stage(s)\n' "$TOTAL"
exit 0
